#!/usr/bin/env python3
"""Writes the module definition of what d.exe exports to game.dll: every
symbol the game's objects need that the port's own objects define (the
PS1 library replacements: VSync, CdRead, ...; psx_exit, psx_safe_point,
psx_rand).  What neither defines (memcpy, printf) comes from the C
runtime.  Called by build.ninja (configure.py):

    python tools/exe_exports.py build/gen/d.def @<list of the game's objects>

The port's objects are all the others under build/obj (not game/, gen/).
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NM = os.path.join(HERE, 'tools', 'llvm-mingw', 'bin', 'llvm-nm.exe')
OBJ = os.path.join(HERE, 'build', 'obj')
DATA_TYPES = 'BDRbdr'                   # (variables: exported as DATA)


def symbols(objects):
    """({defined name: nm type}, {undefined names}) of the objects."""
    defined, undefined = {}, set()
    for i in range(0, len(objects), 100):
        out = subprocess.run([NM] + objects[i:i + 100], check=True, capture_output=True,
                             text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) == 2 and parts[0] == 'U':
                undefined.add(parts[1])
            elif len(parts) == 3 and parts[1] in 'TDBRtdbrC':
                if parts[1].isupper():
                    defined[parts[2]] = parts[1]
    return defined, undefined


def main():
    out, listing = sys.argv[1], sys.argv[2]
    with open(listing[1:] if listing.startswith('@') else listing) as f:
        game = f.read().split()
    port = []
    for folder, _, files in os.walk(OBJ):
        rel = os.path.relpath(folder, OBJ).replace('\\', '/')
        if rel.split('/')[0] in ('game', 'gen'):
            continue
        port += [os.path.join(folder, name) for name in files if name.endswith('.o')]
    game_defined, game_needs = symbols(game)
    port_defined, _ = symbols(sorted(port))
    exports = sorted(name for name in game_needs - set(game_defined) if name in port_defined)
    lines = ['; GENERATED by tools/exe_exports.py: what game.dll takes from d.exe',
             'LIBRARY d.exe', 'EXPORTS']
    for name in exports:
        plain = name[1:] if name.startswith('_') else name      # (i686: C names get a "_")
        lines.append(f'    {plain}' + (' DATA' if port_defined[name] in DATA_TYPES else ''))
    text = '\n'.join(lines) + '\n'
    # (written only when it changes: ninja's restat then leaves game.dll be)
    if not os.path.exists(out) or open(out).read() != text:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        open(out, 'w', newline='\n').write(text)


if __name__ == '__main__':
    main()
